"""
Problem 3: additional figures.

Reads ``results/problem_3/ratio_analysis.txt`` (produced by
``python -m src.main_model``) and renders the six extra charts that appear in
the paper. All outputs are written next to the input file.

Originally generated by Doubao AI and later moved out of the git-ignored
``results/`` directory so that a fresh clone can reproduce them.

Run with:
    python -m src.p3_extra_plots
"""

import re
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd
import seaborn as sns
from scipy import stats

REPO_ROOT = Path(__file__).resolve().parents[1]
RESULT_DIR = REPO_ROOT / "results" / "problem_3"
INPUT_FILE = RESULT_DIR / "ratio_analysis.txt"

# -------------------------- 1. Global Settings: Font & Display --------------------------
plt.rcParams["font.sans-serif"] = ["DejaVu Sans"]  # English font, no Chinese needed
plt.rcParams["axes.unicode_minus"] = False
plt.rcParams["figure.figsize"] = (12, 7)
plt.rcParams["savefig.dpi"] = 300
plt.rcParams["figure.dpi"] = 100


def _read_text(path):
    """Decode the report, tolerating files written with the Windows default (GBK) codec."""
    data = path.read_bytes()
    for encoding in ("utf-8", "gbk"):
        try:
            return data.decode(encoding)
        except UnicodeDecodeError:
            continue
    return data.decode("utf-8", errors="replace")


# -------------------------- 2. Read and Parse ratio_analysis.txt --------------------------
def read_data(file_path=INPUT_FILE):
    """Read the text report and extract the ratio/time/cost table into a DataFrame."""
    pattern = re.compile(
        r"太空电梯比例: (\d+\.\d+)%.*?传统火箭比例: (\d+\.\d+)%.*?所需时间: (\d+\.\d+) 年.*?总成本: (\d+\.?\d*)",
        re.DOTALL,
    )
    rows = []
    content = _read_text(file_path)
    for match in pattern.findall(content):
        elevator_ratio, rocket_ratio, time_need, total_cost = (float(v) for v in match)
        rows.append([elevator_ratio, rocket_ratio, time_need, total_cost])

    df = pd.DataFrame(
        rows,
        columns=[
            "Elevator Ratio (%)",
            "Rocket Ratio (%)",
            "Time Required (Yr)",
            "Total Cost",
        ],
    )
    # Convert total cost to billions for better display
    df["Total Cost (Billion)"] = df["Total Cost"] / 10**9
    return df


def _save(fig_name):
    """Save the current figure into the Problem 3 results directory."""
    path = RESULT_DIR / fig_name
    plt.savefig(path)
    print(f"Chart saved: {path}")


# -------------------------- 3. Plot All Charts in English --------------------------
def plot_all_charts(df):
    x = df["Elevator Ratio (%)"]
    cost_billion = df["Total Cost (Billion)"]
    rocket_ratio = df["Rocket Ratio (%)"]

    # ---------- Chart 1: Total cost vs elevator ratio ----------
    plt.figure()
    plt.plot(x, cost_billion, color="#2E86AB", linewidth=2.5, marker="o", markersize=4, label="Total Cost")
    plt.title("Total Cost Trend vs Space Elevator Ratio", fontsize=16, pad=20)
    plt.xlabel("Space Elevator Ratio (%)", fontsize=12)
    plt.ylabel("Total Cost (Billion USD)", fontsize=12)
    plt.grid(True, alpha=0.3, linestyle="-")
    plt.legend(fontsize=10)
    plt.tight_layout()
    _save("1_cost_trend_line.png")

    # ---------- Chart 2: Stacked ratio distribution ----------
    plt.figure()
    plt.fill_between(x, 0, x, color="#A23B72", alpha=0.7, label="Space Elevator Ratio")
    plt.fill_between(x, x, 100, color="#F18F01", alpha=0.7, label="Conventional Rocket Ratio")
    plt.title("Stacked Distribution of Elevator & Rocket Ratios", fontsize=16, pad=20)
    plt.xlabel("Space Elevator Ratio (%)", fontsize=12)
    plt.ylabel("Ratio (%)", fontsize=12)
    plt.ylim(0, 100)
    plt.grid(True, alpha=0.3)
    plt.legend(fontsize=10)
    plt.tight_layout()
    _save("2_ratio_stacked_area.png")

    # ---------- Chart 3: Scatter plot with trend line ----------
    plt.figure()
    plt.scatter(x, cost_billion, color="#C73E1D", s=30, alpha=0.8, label="Actual Data Points")
    slope, intercept, r_value, _p_value, _std_err = stats.linregress(x, cost_billion)
    plt.plot(
        x,
        slope * x + intercept,
        color="#000000",
        linewidth=2,
        linestyle="--",
        label=f"Trend Line (R²={r_value**2:.4f})",
    )
    plt.title("Scatter Plot of Cost vs Elevator Ratio (with Trend Line)", fontsize=16, pad=20)
    plt.xlabel("Space Elevator Ratio (%)", fontsize=12)
    plt.ylabel("Total Cost (Billion USD)", fontsize=12)
    plt.grid(True, alpha=0.3)
    plt.legend(fontsize=10)
    plt.tight_layout()
    _save("3_cost_scatter_trend.png")

    # ---------- Chart 4: Horizontal bars comparing both ratios ----------
    plt.figure(figsize=(12, 8))
    top_n = min(20, len(df))
    x_bar = x[:top_n].astype(str)
    plt.barh(x_bar, x[:top_n], color="#2E86AB", alpha=0.8, label="Space Elevator Ratio", height=0.4)
    plt.barh(
        [f"{i}-" for i in x_bar],
        rocket_ratio[:top_n],
        color="#F18F01",
        alpha=0.8,
        label="Conventional Rocket Ratio",
        height=0.4,
    )
    plt.title(f"Comparison of Elevator & Rocket Ratios (First {top_n} Groups)", fontsize=16, pad=20)
    plt.xlabel("Ratio (%)", fontsize=12)
    plt.ylabel("Space Elevator Ratio (%)", fontsize=12)
    plt.grid(True, alpha=0.3, axis="x")
    plt.legend(fontsize=10)
    plt.tight_layout()
    _save("4_ratio_horizontal_bar.png")

    # ---------- Chart 5: Total cost bars ----------
    plt.figure(figsize=(15, 7))
    show_n = min(30, len(df))
    plt.bar(x[:show_n], cost_billion[:show_n], color="#A23B72", alpha=0.8, width=0.8)
    plt.title(f"Total Cost by Space Elevator Ratio (First {show_n} Groups)", fontsize=16, pad=20)
    plt.xlabel("Space Elevator Ratio (%)", fontsize=12)
    plt.ylabel("Total Cost (Billion USD)", fontsize=12)
    plt.grid(True, alpha=0.3, axis="y")
    plt.tight_layout()
    _save("5_cost_bar.png")

    # ---------- Chart 6: Correlation heatmap ----------
    plt.figure(figsize=(10, 8))
    corr_data = df[
        ["Elevator Ratio (%)", "Rocket Ratio (%)", "Time Required (Yr)", "Total Cost (Billion)"]
    ].corr()
    sns.heatmap(
        corr_data,
        annot=True,
        cmap="RdBu_r",
        vmin=-1,
        vmax=1,
        fmt=".4f",
        linewidths=0.5,
        annot_kws={"fontsize": 10},
    )
    plt.title("Correlation Heatmap of All Indicators", fontsize=16, pad=20)
    plt.tight_layout()
    _save("6_indicator_correlation_heatmap.png")


# -------------------------- 4. Main Execution --------------------------
def main():
    if not INPUT_FILE.exists():
        raise SystemExit(
            f"Missing {INPUT_FILE}. Run `python -m src.main_model` first."
        )
    df = read_data()
    if df.empty:
        raise SystemExit(
            f"No valid records parsed from {INPUT_FILE}; check the file format."
        )
    plot_all_charts(df)
    print("All charts generated and saved successfully!")


if __name__ == "__main__":
    main()
